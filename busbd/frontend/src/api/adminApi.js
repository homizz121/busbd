import api from './axios'
export const getDashboard = () => api.get('/admin/dashboard')
export const getAllBuses = () => api.get('/admin/buses')
export const createBus = (data) => api.post('/admin/buses', data)
export const updateBus = (id, data) => api.put(`/admin/buses/${id}`, data)
export const deleteBus = (id) => api.delete(`/admin/buses/${id}`)
export const getAllTrips = () => api.get('/admin/trips')
export const createTrip = (data) => api.post('/admin/trips', data)
export const createTripsRange = (data) => api.post('/admin/trips/range', data)
export const cancelTrip = (id) => api.delete(`/admin/trips/${id}`)
export const getAllBookings = (params) => api.get('/admin/bookings', { params })
export const cancelAdminBooking = (id) => api.delete(`/admin/bookings/${id}`)
export const getAllUsers = () => api.get('/admin/users')
export const toggleUserStatus = (id) => api.put(`/admin/users/${id}/status`)
export const getAllWaitlist = () => api.get('/admin/waitlist')
export const promoteWaitlist = (id) => api.post(`/admin/waitlist/${id}/promote`)
export const deleteWaitlistEntry = (id) => api.delete(`/admin/waitlist/${id}`)
export const blockSeat = (busId, data) => api.post(`/admin/buses/${busId}/seats/block`, data)
export const unblockSeat = (busId, seatNumber) => api.delete(`/admin/buses/${busId}/seats/block/${seatNumber}`)
export const changeSeatType = (busId, seatNumber, data) => api.put(`/admin/buses/${busId}/seats/${seatNumber}/type`, data)
export const getRevenue = (params) => api.get('/admin/revenue', { params })
export const getSettings = () => api.get('/admin/settings')
export const updateSettings = (data) => api.put('/admin/settings', data)
